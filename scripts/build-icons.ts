/**
 * Builds public/icons.svg, a sprite of the Lucide icons gather uses (ISC licence, see public/vendor/LICENSES.md).
 *
 *   npm pack lucide-static@0.460.0 && tar xzf lucide-static-0.460.0.tgz
 *   node scripts/build-icons.ts package/icons
 *
 * Stroke attributes are stripped from each symbol so CSS (.i in ui.css) sets one stroke width
 * (1.75) for every icon. Add a name to ICONS, rebuild, then use icon('name') in JS or
 * <svg class="i"><use href="/icons.svg#i-name"/></svg> in HTML.
 */
const fs = require('node:fs') as typeof import('node:fs');
const path = require('node:path') as typeof import('node:path');

const ICONS = [
  'arrow-down', 'arrow-up', 'arrow-up-right', 'check', 'chevron-down', 'chevron-left', 'chevron-right', 'circle', 'circle-dot', 'circle-help', 'clock',
  'copy', 'eye', 'eye-off', 'file-text', 'flag', 'image', 'layout-dashboard', 'link', 'lock', 'lock-open', 'log-out', 'message-square', 'mic', 'mic-off',
  'monitor', 'monitor-up', 'palette', 'pause', 'phone', 'play', 'plus', 'qr-code', 'radio', 'repeat', 'rotate-ccw', 'search', 'send', 'shield-check',
  'sliders-horizontal', 'sparkles', 'square', 'trash-2', 'upload', 'user', 'users', 'video', 'video-off', 'x',
  'activity', 'log-in', 'user-plus', 'monitor-x', 'presentation', 'command',
  'volume-2', 'volume-x', 'maximize', 'hand', 'smile', 'scissors', 'heart',
  ['pip', 'picture-in-picture-2'], ['tip', 'circle-dollar-sign'], // [id in the sprite, Lucide file]
] as const;

function main(): void {
  const src = process.argv[2];
  if (!src || !fs.existsSync(src)) { console.error('Usage: node scripts/build-icons.ts <lucide-static/icons dir>'); process.exit(1); }
  const symbols = ICONS.map((entry) => {
    const [name, file] = typeof entry === 'string' ? [entry, entry] : entry;
    const raw = fs.readFileSync(path.join(src, `${file}.svg`), 'utf8');
    const body = raw.replace(/<!--[\s\S]*?-->/g, '').replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '')
      .replace(/\s+/g, ' ').replace(/ \/>/g, '/>').replace(/> </g, '><').trim();
    return `<symbol id="i-${name}" viewBox="0 0 24 24">${body}</symbol>`;
  });
  const out = `<svg xmlns="http://www.w3.org/2000/svg"><!-- Lucide v0.460.0, ISC licence. Generated by scripts/build-icons.ts -->\n${symbols.join('\n')}\n</svg>\n`;
  const dest = path.resolve(__dirname, '..', 'public', 'icons.svg');
  fs.writeFileSync(dest, out);
  console.log(`${ICONS.length} icons → ${path.relative(process.cwd(), dest)} (${out.length} bytes)`);
}
main();
